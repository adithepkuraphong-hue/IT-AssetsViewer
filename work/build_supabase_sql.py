def main():
    data = json.loads(DATA_PATH.read_text(encoding="utf-8"))
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    schema = build_schema()
    seed = build_seed(data)
    (OUT_DIR / "asset-control-schema.sql").write_text(schema, encoding="utf-8")
    (OUT_DIR / "asset-control-seed.sql").write_text(seed, encoding="utf-8")
    (OUT_DIR / "asset-control-full.sql").write_text(schema + "\n" + seed, encoding="utf-8")
    summary = {
        "schema": str(OUT_DIR / "asset-control-schema.sql"),
        "seed": str(OUT_DIR / "asset-control-seed.sql"),
        "full": str(OUT_DIR / "asset-control-full.sql"),
        "computerAssets": len(data.get("computerAssets", [])),
        "otherAssets": len(data.get("otherAssets", [])),
        "maintenanceHistory": len(data.get("maintenanceHistory", [])),
        "maintenanceRequests": len(data.get("maintenanceRequests", [])),
        "checkoutRecords": len(data.get("checkoutRecords", [])),
        "users": len(data.get("users", [])),
    }
    print(json.dumps(summary, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
