def sql(value):
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def insert_statement(table, rows, columns, conflict=None):
    if not rows:
        return f"-- {table}: no rows to seed\n"
    values = []
    for row in rows:
        values.append("(" + ", ".join(sql(row.get(column)) for column in columns) + ")")
    conflict_sql = f"\n{conflict}" if conflict else ""
    return (
        f"insert into public.{table} ({', '.join(columns)}) values\n"
        + ",\n".join(values)
        + conflict_sql
        + ";\n"
    )


